from typing import List
from collections import deque


class Solution:
    """
    LeetCode 239. 滑动窗口最大值

    给定数组 nums 和窗口大小 k，窗口从左往右逐格滑动，
    求每个窗口位置里的最大值，返回长度为 n - k + 1 的数组。
    例如 nums = [1,3,-1,-3,5,3,6,7], k = 3 -> [3,3,5,5,6,7]

    做法：单调队列（用 deque 存下标），队列始终保持两条性质：
        * 下标从队头到队尾递增 —— 队头 q[0] 是窗口里最靠左的候选，也最早过期；
        * 对应的 nums 值从队头到队尾严格递减 —— 所以 q[0] 就是当前窗口的最大值。
    于是「取窗口最大值」变成了「读队头」，均摊 O(1)，整体 O(n)。

    deque 两端的职责是分开的，别看混：
        q.pop()      —— 从「队尾」弹，用来挤掉那些「又小、又靠左」的下标；
        q.popleft()  —— 从「队头」弹，用来扔掉已经滑出窗口的下标。
    """

    def maxSlidingWindow(self, nums: List[int], k: int) -> List[int]:
        ans = []
        q = deque()
        for i, x in enumerate(nums):
            # 1 入：维护「值递减」，把队尾所有 <= x 的下标挤掉。
            #   为什么可以放心挤掉？因为 x 比它们大，而且 x 的下标 i 更靠右（更晚滑出窗口），
            #   所以只要 x 还在窗口里，它们就永远不可能成为任何窗口的最大值。
            #   （用 <= 而不是 <：相等也挤掉，队列里就不会留重复的等大值。）
            while q and nums[q[-1]] <= x:
                q.pop()
            q.append(i)
            # 2 出：把已经滑出窗口的下标从队头扔掉。
            #   处理到下标 i 时，窗口覆盖的范围是 [i-k+1, i]，
            #   所以队头 q[0] 合法（还在窗口内）等价于 q[0] >= i-k+1，
            #   也就是 i - q[0] <= k-1；
            #   反过来，i - q[0] >= k 就说明 q[0] 已经过期、必须扔掉。
            #   这里用 if 而不是 while 就够了：i 每轮只前进一格，
            #   所以一步最多只有一个下标过期。
            if i - q[0] >= k:  # 等价写法：if q[0] <= i - k:
                q.popleft()
            # 3 记录答案：前 k-1 个位置窗口还没填满，从 i == k-1 起窗口才首次完整；
            #   此后每一轮都能产出答案。队头就是当前窗口的最大值。
            if i >= k - 1:
                ans.append(nums[q[0]])

        return ans


if __name__ == "__main__":
    s = Solution()
    print(s.maxSlidingWindow([1,3,-1,-3,5,3,6,7], 3))  # [3,3,5,5,6,7]
    print(s.maxSlidingWindow([1], 1))  # [1]
    print(s.maxSlidingWindow([1,-1], 1))  # [1,-1]
    print(s.maxSlidingWindow([9,11], 2))  # [11]
    print(s.maxSlidingWindow([4,-2], 2))  # [4]


# =============================================================================
# 关于窗口边界（这里是唯一容易写错的地方）
# =============================================================================
#
# 处理到下标 i 时，窗口覆盖的下标范围是
#
#       [i - k + 1,  i]
#
# 例如 i = 4、k = 3 时，窗口是 [2, 4]。
#
# 所以队头 q[0] 「还没过期」的条件是
#
#       q[0] >= i - k + 1      <=>      i - q[0] <= k - 1
#
# 反过来，需要把它扔掉的条件就是
#
#       q[0] <  i - k + 1      <=>      i - q[0] >= k      <=>   q[0] <= i - k
#
# 也就是代码里那句 `if i - q[0] >= k: q.popleft()`。
#
# 常见错误是漏掉那个 -1，写成 `i - q[0] > k`（等价于 q[0] < i - k），
# 那会比正确的时机晚一步才扔掉队头，于是窗口里混进了过期的老元素。
# 例如 nums = [9, 1, 1], k = 2：
#       i=2 时窗口是 [1, 2]，下标 0 已经出界，必须扔掉，答案才是 [9, 1]；
#       写成 > k 的话下标 0 会被留下，读到过期的 9，答案错成 [9, 9]。
#
# 另外顺带一提：因为第 1 步刚把 i 自己放进队列，第 2 步最多只会把 q[0] 弹掉，
# 队列不会变空，所以第 3 步直接读 q[0] 是安全的（前提是 k >= 1）。
