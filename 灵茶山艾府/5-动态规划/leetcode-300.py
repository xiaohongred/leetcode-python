from functools import cache


class Solution:
    """
    LeetCode 300. 最长递增子序列（LIS）

    给定一个整数数组 nums，求「最长严格递增子序列」的长度。
    子序列不要求连续，只要保持原有的前后顺序；
    「严格」指后一个数必须比前一个大，所以 [7, 7, 7] 的答案是 1。

    思路（记忆化搜索）：定义 dfs(i) 为「以 nums[i] 结尾」的最长递增子序列长度，
    枚举所有能接在 nums[i] 前面的下标 j（要求 nums[j] < nums[i]）取最大值。
    时间 O(n²)，空间 O(n)。
    """

    def lengthOfLIS(self, nums: list[int]) -> int:
        n = len(nums)

        @cache
        def dfs(i):
            """
            返回：以 nums[i] 作为「最后一个元素」的最长严格递增子序列长度。

            注意「以 nums[i] 结尾」这个限定 —— 它是本题能写出状态转移的关键：
            只有把结尾钉死，才能只往前看、只去找比它小的数。
            """
            res = 0  # 记录「接在 nums[i] 前面的那一段」最长能有多长
            for j in range(i):
                # 只有比 nums[i] 小的数，才有资格排在它前面
                if nums[j] < nums[i]:
                    # 枚举每个合法的前驱 j，看接到谁后面能让子序列更长
                    res = max(res, dfs(j))
            # 无论前面能不能接上，nums[i] 自身都算一个元素，所以 +1；
            # （res 一直是 0，说明前面没有比它小的数，答案就是它自己，长度 1）
            return res + 1

        # 最长的子序列可能以任意下标结尾，所以每种结尾都试一下，取最大值
        ans = 0
        for i in range(n):
            ans = max(ans, dfs(i))
        return ans


if __name__ == "__main__":
    s = Solution()
    print(s.lengthOfLIS([10, 9, 2, 5, 3, 7, 101, 18]))  # 4 -> 如 [2, 3, 7, 101]
    print(s.lengthOfLIS([0, 1, 0, 3, 2, 3]))           # 4 -> 如 [0, 1, 2, 3]
    print(s.lengthOfLIS([7, 7, 7, 7, 7, 7, 7]))        # 1 -> 严格递增，7 接不到 7 后面


# =============================================================================
# 补充说明
# =============================================================================
#
# 1) 为什么外面还要再套一层 max？
#    dfs(i) 的定义里「必须包含 nums[i]」，但最长的那条子序列可能以任何下标结尾，
#    所以答案是 max(dfs(0), ..., dfs(n-1))，而不是 dfs(n-1)。
#    （这一点和 LCS / 编辑距离那种「前缀对前缀」的定义不同，别混起来。）
#
# 2) 复杂度：状态共 n 个，每个状态要遍历 O(n) 个前驱，所以时间 O(n²)；
#    加了 @cache 后每个状态只算一次，额外空间 O(n)（不含递归栈）。
#
# 3) n 到 10^5 量级时 O(n²) 会超时，那时要用「贪心 + 二分」的 O(n log n) 解法：
#    维护数组 tails，tails[k] 表示「长度 k+1 的递增子序列」能取到的最小结尾值；
#    对每个 x 用 bisect_left(tails, x) 找到第一个 >= x 的位置替换（找不到就追加），
#    最后 len(tails) 就是答案。严格递增用 bisect_left，允许相等则用 bisect_right。
