from typing import List
from functools import cache


class Solution:
    """
    LeetCode 188. 买卖股票的最佳时机 IV（最多 k 次交易）

    给定每天的价格 prices，最多可以完成 k 笔交易（一笔 = 买入 + 卖出），
    同一时刻最多持有一股，求能获得的最大利润。
    例如 k = 2, prices = [3,2,6,5,0,3] -> 7（2 买 6 卖赚 4，0 买 3 卖赚 3）。

    这就是 122 / 309 那套「持仓 / 空仓」状态机，再加一维：交易次数额度。

    ── 状态定义 ────────────────────────────────────────────────────────
        dfs(i, j, hold) = 只考虑 prices[0..i]，在「第 i 天收盘时」状态为 hold，
                          并且「这 i+1 天里卖出的次数不超过 j 次」时的最大利润

        i   ：天数下标（从 n-1 往前推）
        j   ：卖出次数的「预算上限」——到第 i 天为止最多允许卖出 j 次
        hold：第 i 天收盘时是否持有股票（True 持仓 / False 空仓）

    为什么数「卖出次数」就等于数「交易次数」？因为一笔完整交易恰好含一次卖出，
    买卖一一对应，所以「最多 k 笔交易」= 「最多卖出 k 次」。

    ★ 注意 j 是「累计允许用掉多少」，不是「还剩多少」：
      初始调用传的是 j = k（总共最多卖 k 次）；而往回推一天时，如果那天发生了卖出，
      j 就减 1 —— 因为「越早的日子，累计能卖出的次数自然越少」。所以
      dfs(n-1, k, False) 表达的就是「这 n 天里最多卖 k 次、最后空仓」。

    ── 三种跳转 ────────────────────────────────────────────────────────
        什么都不做：dfs(i-1, j, hold)
        今天买入  ：dfs(i-1, j, False) - prices[i]   ← 买入不占用卖出额度，j 不变
        今天卖出  ：dfs(i-1, j-1, True) + prices[i]  ← 今天吃掉一次卖出额度，
                                                       所以到昨天为止只能卖 j-1 次
    """

    def maxProfit(self, k: int, prices: List[int]) -> int:
        """写法一：记忆化搜索（自顶向下）。"""
        n = len(prices)

        @cache
        def dfs(i, j, hold):
            """
            返回：只考虑 prices[0..i]、第 i 天收盘时状态为 hold、
                  且这些天里「卖出次数不超过 j 次」时能获得的最大利润。
                  若这个组合根本不可能（额度成了负数、或状态本身不合法），返回 -inf。
            """
            # 额度已经用到负数：连一次卖出都不允许，这条路不可能再构成合法方案。
            # 这个判断必须排在 i < 0 之前，否则 j = -1 这种非法状态会被误当成合法边界。
            if j < 0:
                return float('-inf')

            # 一天都还没考虑：空仓利润 0；此刻持仓根本不存在，记 -inf
            if i < 0:
                return float('-inf') if hold else 0

            if hold:
                # 第 i 天收盘持仓，两种来源取较大者：
                #   1) 昨天就持仓，今天什么都不做 -> dfs(i-1, j, True)
                #   2) 今天买入                  -> dfs(i-1, j, False) - prices[i]
                #      买入不消耗卖出额度，所以 j 原样传给昨天。
                #      （即使 j == 0 也允许买，但买完就再也不许卖了，
                #        最终只能停在持仓状态，不会进入答案）
                return max(dfs(i-1, j, True), dfs(i-1, j, False)-prices[i])
            # 第 i 天收盘空仓，两种来源取较大者：
            #   1) 昨天就空仓，今天什么都不做 -> dfs(i-1, j, False)
            #   2) 今天卖出                  -> dfs(i-1, j-1, True) + prices[i]
            #      今天已经花掉一次卖出额度，所以到昨天为止最多只能卖 j-1 次
            return max(dfs(i-1, j, False), dfs(i-1, j-1, True)+prices[i])

        # 用完全部 n 天、总共最多卖 k 次、收盘空仓
        return dfs(n-1, k, False)

    def maxProfitDp(self, k: int, prices: List[int]) -> int:
        """
        写法二：三维表递推（自底向上）。

        f[i][j][hold]：用「前 i 天」（prices[0..i-1]）、收盘状态为 hold、
                       且「已买入次数不超过 j-1 次」时的最大利润。

        ★ 注意表里的 j 和 dfs 里的 j 数的不是同一件事：
            dfs 的 j 卡的是「卖出次数」，
            表的 j 卡的是「买入次数」（第 j 列允许买 j-1 次）。
        对最终「空仓」的状态来说买入次数 = 卖出次数 = 交易笔数，所以两种计数
        都等价于「最多 k 笔交易」，只是从不同一侧去数，两边下标因此并不一一对应。

        表的第 0 列是「哨兵列」：它表示一次都不许买，整列保持 -inf。于是
            f[i+1][1][1] = max(f[i][1][1], f[i][0][0] - p) = -inf
        天然表达了「没买过就不可能持仓」，不用再写额外的 if。
        """
        n = len(prices)

        # 行 = 前 i 天（0..n）；列 = 0..k+1（第 0 列是 -inf 哨兵，第 j 列允许买 j-1 次）；
        # 最后一维 = 0 空仓 / 1 持仓
        f = [[[float('-inf')]*2 for _ in range(k+2)] for _ in range(n+1)]
        # 边界：一天都还没考虑时，只要不是哨兵列，空仓利润都是 0。
        # 为什么要给所有列都赋 0，而不是只给某列？
        #   因为「什么都不做」允许你从任意一列直接开始，这正是「最多 k 次」而不是
        #   「恰好 k 次」的关键 —— 后面那些列可以靠什么都不做的自环一路带着 0 传下来。
        for j in range(1, k+2):
            f[0][j][0] = 0

        for i, p in enumerate(prices):   # p = prices[i]，用第 i 行推出第 i+1 行
            for j in range(1, k+2):
                # 第 i+1 天收盘空仓：
                #   不动   -> 沿用上一行的同一列（什么都不做，不消耗买入次数）
                #   今天卖 -> 昨天必须持仓，卖出收钱 +p；
                #             卖出不改变「已买入次数」，所以还在同一列 j
                f[i+1][j][0] = max(f[i][j][0], f[i][j][1]+p)
                # 第 i+1 天收盘持仓：
                #   不动   -> 沿用上一行的同一列
                #   今天买 -> 昨天必须空仓，买入花钱 -p；
                #             ★ 买入会把「已买入次数」用掉一次，所以昨天在 j-1 列
                #               （j-1 == 0 时读到哨兵列的 -inf，表示没额度可买了）
                f[i+1][j][1] = max(f[i][j][1], f[i][j-1][0]-p)

        # 答案：用完全部 n 天、最多买 k 次（即第 k+1 列）、收盘空仓
        return f[n][k+1][0]


if __name__ == "__main__":
    s = Solution()
    print(s.maxProfit(2, [3,2,6,5,0,3]))  # 7
    print(s.maxProfit(2, [2,4,1]))        # 2
    print(s.maxProfit(2, [3,2,6,5,0,3]))  # 7


# =============================================================================
# 补充说明
# =============================================================================
#
# 1) 为什么 dfs 的 j 和表的 j 数的不是同一个东西？
#    两者都在限制「交易次数」，只是一个从「卖出」这一侧计数、一个从「买入」这一侧计数：
#      * dfs：卖出时扣额度（j -> j-1），入口是 dfs(n-1, k, False)；
#      * 表 ：买入时占额度（第 j 列允许买 j-1 次），出口是 f[n][k+1][0]。
#    对最终的空仓状态来说，买入次数 = 卖出次数 = 交易笔数，所以两种写法都等价于
#    「最多 k 笔交易」；但两边的下标因此对不齐（表里那个 +1 是给哨兵列 0 腾位置）。
#
# 2) 为什么表要单独留一列 j = 0？
#    因为「买入」要往「额度更少」的一侧回退一格，而额度最少就是「一次都没买过」。
#    再往前就是「买过 -1 次」这种非法状态，用一整列 -inf 当哨兵来表示，
#    这样代码里不用写额外的 if，直接 max 就行。
#
# 3) 复杂度
#    状态数 O(n · k)，每个状态 O(1) 转移：
#      * dfs：时间 O(n · k)，额外空间 O(n · k)（记忆化缓存的规模）+ 递归栈；
#      * 表 ：时间 O(n · k)，空间 O(n · k)（每行只依赖上一行，其实还能再滚掉一维）。
#
# 4) 一个常用剪枝：若 k >= n // 2，额度就永远用不完（n 天最多也只能完成 n//2 笔交易），
#    此时题目退化成 122 题，答案就是 Σ max(0, prices[i] - prices[i-1])（吃满所有上涨段），
#    可以直接返回，省下 O(n · k) 的开销。
