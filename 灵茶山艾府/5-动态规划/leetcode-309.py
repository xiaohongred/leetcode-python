from functools import cache
from math import inf


class Solution:
    """
    LeetCode 309. 买卖股票的最佳时机含冷冻期

    和 122 题（可以无限次交易）几乎一样，只多了一条限制：
    **卖出股票的第二天不能买入**（冷冻期为 1 天）。
    注意这条限制管的是「买入」：卖出当天照常卖，买完第二天也照常能卖。

    ── 状态含义（hold 到底是什么）──────────────────────────────────────
        dfs(i, hold) = 只考虑 prices[0..i]，在「第 i 天收盘时」手里是否持仓为 hold
                       的情况下，能获得的最大利润
        hold = True  持仓（手里握着股票）
        hold = False 空仓（手里没有股票）

    ★ hold 描述的是「第 i 天收盘时的状态」，而不是「第 i 天做了什么」。
      这是最容易绕晕的一点：
          dfs(3, True) 只说明第 3 天收盘时手里有股票，
          它可能是第 3 天刚买的，也可能是前天买的、一直拿着没动。

      正因为它是「状态」而不是「动作」，买入/卖出才必须表示成
      「昨天状态 -> 今天状态」的跳转，而不是单独的一个参数：
          买入     = False -> True （今天花钱买入）
          卖出     = True  -> False（今天收钱卖出）
          什么都不做 = 状态原地不动（自环）
      画成状态机就是这样（两条自环省略了）：

          空仓 False ──── 买入 -prices[i] ────▶ 持仓 True
               ▲                                   │
               └──────── 卖出 +prices[i] ◀─────────┘

          另外每个状态都允许「什么都不做」，也就是一条状态不变的自环。

      一个布尔值就够，是因为题目规定「同一时刻最多只能持有一股」，
      手里只有「有 / 没有」两种情况，不存在「持有几股」。
      （在递推版里这个 bool 就变成了第二个维度下标：f[i][0] 空仓、f[i][1] 持仓。）

      另外要注意：hold 只告诉你「有没有股票」，不告诉你「这个状态是怎么来的」——
      它区分不了「早就空仓」和「昨天刚卖掉」。而这恰恰就是冷冻期不能直接沿用
      dfs(i-1, False) 的原因（详见文件末尾的长注释）。

    ── 三种来路 ────────────────────────────────────────────────────────
    进入 dfs(i, hold) 时，hold 是「今天收盘时要达到的状态」，
    所以只需枚举「昨天是哪种状态、经过什么动作」能变成它：

        今天收盘持仓 True   ┐ 昨天就持仓 + 不动   -> dfs(i-1, True)
                            └ 昨天空仓   + 今天买入 -> dfs(i-2, False) - prices[i]
        今天收盘空仓 False  ┐ 昨天就空仓 + 不动   -> dfs(i-1, False)
                            └ 昨天持仓   + 今天卖出 -> dfs(i-1, True) + prices[i]

    买入那一支为什么是 i-2（而不是像 122 题那样用 i-1），见末尾的长注释。
    """

    def maxProfit(self, prices: list[int]) -> int:
        n = len(prices)

        @cache
        def dfs(i, hold):
            """
            参数 hold 就是「第 i 天收盘时手里有没有股票」，取值只有 True / False。
            这里再强调一次：它描述的是**状态**，不是「今天做了什么」。
            所以每进入一次 dfs，需要回答的都是同一个问题：
            「今天收盘要达到 hold 这个状态，昨天得是什么状态、今天得做什么动作？」
            """
            if i < 0:
                # 边界：一天都还没考虑。此刻 hold 的作用是判断「这个状态合不合法」——
                #   空仓是自然的，利润为 0；
                #   持仓根本不存在（还没机会买股票），用 -inf 表示不可达。
                # 若这里也写 0，等于凭空送你一笔免费持仓，答案会偏大。
                return float('-inf') if hold else 0
            if hold:
                # 今天收盘持仓。注意「持仓」并不等于「今天买入」——也可能是早就买了没动。
                # 两种来源取较大者：
                #   1) 昨天就持仓、今天什么都不做（True -> True，自环）-> dfs(i-1, True)
                #   2) 昨天空仓、今天买入（False -> True）             -> 昨天必须「本来」就空仓，
                #      所以写 dfs(i-2, False)，原因见末尾注释
                return max(dfs(i-1, True), dfs(i-2, False) - prices[i])
            # 今天收盘空仓。空仓同样有两种来源，取较大者：
            #   1) 昨天就空仓、今天什么都不做（False -> False，自环）-> dfs(i-1, False)
            #   2) 昨天持仓、今天卖出（True -> False）               -> dfs(i-1, True) + prices[i]
            #      （冷冻期只限制买入，所以这一支不需要往前退两天）
            return max(dfs(i-1, False), dfs(i-1, True) + prices[i])

        # 最后一天收盘还持股没有意义（白白多付一次买入的钱），答案取空仓状态
        return dfs(n-1, False)


# =============================================================================
# 为什么「今天买入」要写 dfs(i-2, False)，而不是像 122 题那样写 dfs(i-1, False)？
# =============================================================================
#
# 先把语义钉死：dfs(i, hold) 描述的是「第 i 天收盘时」的状态。
# 那么在「第 i 天买入」时，前提就是「第 i-1 天收盘时手里是空的」。
#
# 122 题里直接写 dfs(i-1, False) 就够了，因为空仓就是空仓。但加了冷冻期就不行了，
# 因为 dfs(i-1, False) 这个「空仓」有两种来路：
#
#     (a) 早就空仓了，第 i-1 天什么都没做；        -> 今天可以买 ✔
#     (b) 第 i-1 天刚刚把股票卖掉。                -> 今天是冷冻期，不能买 ✘
#
# 也就是说，dfs(i-1, False) 会把「昨天刚卖、今天就买」这种非法方案也当作合法候选，
# 结果自然偏大。问题就出在：它没法区分这两种来路。
#
# 换成 dfs(i-2, False)，意思是「第 i-2 天收盘时就已经空仓」。
# 那么第 i-1 天可以什么都不做 —— 这恰好就是冷冻期该有的样子：
#
#     ... 第 i-2 天收盘空仓 ──> 第 i-1 天什么都不做（冷冻期） ──> 第 i 天买入
#
# 于是第 i-1 天绝不可能是卖出日，冷冻期的限制就被自动满足了。
#
# 会不会漏解？不会。任何「第 i 天买入」的合法方案里，第 i-1 天一定没有卖出，
# 所以第 i-2 天收盘时必然已经空仓：
#     * 要么更早就空仓了 —— dfs 里「什么都不做」的自环会把这份利润一路带到 i-2；
#     * 要么更早卖的     —— 那也早在 i-2 之前就空仓了。
# 所以 dfs(i-2, False) 恰好覆盖了所有合法的「买入前状态」，一个不多一个不少。
#
# 最紧的两条边界可以对着看（i = 5 举例）：
#
#     第 3 天卖出 -> 第 4 天冷冻 -> 第 5 天买入   ✔ 合法，
#         对应 dfs(3, False) = dfs(i-2, False)，正好被算进来；
#     第 4 天卖出 -> 第 5 天买入                  ✘ 非法，
#         它就是靠「不用 dfs(i-1, False)」给排除掉的。
#
# 一句话：**冷冻期限制的是「买入」，所以只需要把「买入」这一支往前多退一天**，
#         卖出那一支 dfs(i-1, True) + prices[i] 完全不用动。
#
# 顺着这个思路，递推版是这样（注意 f[i][0] 变成了 f[i-2][0]，其它都一样）：
#
#     g[0][0] = 0, g[0][1] = -prices[0]                 # 第 0 天收盘
#     g[i][0] = max(g[i-1][0], g[i-1][1] + p[i])        # 空仓：不动 / 第 i 天卖
#     g[i][1] = max(g[i-1][1], g[i-2][0] - p[i])        # 持仓：不动 / 第 i 天买
#       （i-2 < 0 时，g[负数][0] 一律当作 0，即「一天都还没考虑」）
#
# 注意 g[i][1] 用到的是间隔一行的 g[i-2][0]，所以做滚动数组优化时不能只留「昨天」，
# 必须同时留着 f[i-1] 和 f[i-2] 两份 —— 这正是本题和 122 题在优化空间时最大的区别。
