from functools import cache


class Solution:
    """
    LeetCode 1039. 多边形三角剖分的最低得分

    给定一个凸多边形，按顺序给出 n 个顶点的值 values（下标 0..n-1）。
    用 n-3 条互不相交的对角线把它剖分成 n-2 个三角形；
    三角形 (i, j, k) 的得分是三个顶点值之积 values[i]*values[j]*values[k]，
    求所有三角形得分之和的最小值。
    例如 [1,2,3] -> 6，[3,7,4,5] -> 144，[1,3,1,4,1,5] -> 13。

    ── 核心思路：固定一条边，枚举它落在哪个三角形里 ─────────────────────
    这是「区间 DP」：把「顶点 i 到顶点 j 这一段连续边界围成的子多边形」当作状态。
    关键观察是：**在这块子多边形的任意一种剖分里，边 (i, j) 恰好属于一个三角形**。
    设该三角形第三个顶点是 k（i < k < j），那么：
        * 这个三角形贡献得分 values[i] * values[j] * values[k]；
        * 它还顺带把子多边形切成两块互不干扰的小多边形：i..k 与 k..j，
          两边可以各自求最优、再相加。
    于是只需枚举 k：

        dfs(i, j) = min over k in (i, j) of  dfs(i, k) + dfs(k, j) + v[i]*v[j]*v[k]

    边界：i + 1 == j 时子多边形只剩一条边（两个顶点），凑不出三角形，得分 0。

    两种写法是同一套状态的不同实现：
        写法一 minScoreTriangulation    记忆化搜索   dfs(i, j)
        写法二 minScoreTriangulationDp  区间表递推   f[i][j]
    """

    def minScoreTriangulation(self, values: list[int]) -> int:
        """写法一：记忆化搜索（自顶向下）。"""
        n = len(values)
        v = values  # 起个短名字，下面写乘积时清爽一点

        @cache
        def dfs(i, j):
            """
            返回：把「顶点 i, i+1, ..., j 这段连续边界围成的子多边形」
                  完整剖分所需的最低得分。

            i：子多边形最左端的顶点下标
            j：子多边形最右端的顶点下标（i < j）
            """
            if i + 1 == j:
                # 只剩一条边（两个顶点），是个退化多边形，没有三角形要剖，得分 0。
                # 注意边界是 i + 1 == j 而不是 i == j：单个顶点连边都没有，
                # 根本不会作为子问题出现。
                return 0

            res = float('inf')
            # 枚举「边 (i, j) 所在三角形」的第三个顶点 k。
            # 因为是凸多边形、顶点又是按顺序给的，合法的 k 恰好是 (i, j) 之间所有下标。
            for k in range(i+1, j):
                # 三角形 (i, k, j) 的得分 + 左右两块子多边形各自的最低得分
                res = min(res, dfs(i, k) + dfs(k, j) + v[i]*v[j]*v[k])
            return res

        return dfs(0, n-1)

    def minScoreTriangulationDp(self, values: list[int]) -> int:
        """
        写法二：区间表递推（自底向上）。

        与写法一的对应关系：f[i][j] <==> dfs(i, j)，一一对应。
        """
        n = len(values)

        # f[i][j]：子多边形 i..j 的最低剖分得分（只用到 i < j 的上三角部分）。
        # 整体初始化为 0，其中 f[i][i+1] 恒为 0 —— 这正好就是写法一里
        # `if i + 1 == j: return 0` 那条边界，所以下面不用再单独处理。
        f = [[0]*n for _ in range(n)]

        # ★ 遍历顺序：i 从 n-3 递减到 0，j 从 i+2 递增到 n-1。
        #   1) i 为什么从 n-3 开始？因为只有区间长度 j-i >= 2 才需要枚举分割点 k，
        #      而最大的 i 必须满足 i+2 <= n-1，即 i <= n-3；比它大的都是边界情况。
        #   2) 为什么这个方向能保证「用到的格子都已填好」？f[i][j] 只依赖两类格子：
        #        f[i][k] —— 本行、更靠左（j 正着扫，已经算过）
        #        f[k][j] —— 下面的行（i 倒着扫，那些行已经算过）
        #      两者都不会用到还没填的格子。
        for i in range(n-3, -1, -1):
            for j in range(i+2, n):
                res = float('inf')
                for k in range(i+1, j):
                    # 同样枚举边 (i, j) 所在三角形的第三个顶点 k
                    # 注意 k 可以取到 i+1 或 j-1，此时 f[i][i+1] / f[j-1][j] 就是
                    # 初始化里的 0，正好等于写法一里的边界情况。
                    res = min(res, f[i][k] + f[k][j] + values[i]*values[k]*values[j])
                f[i][j] = res

        return f[0][n-1]  # 整个多边形 0..n-1 的答案


if __name__ == "__main__":
    s = Solution()
    print(s.minScoreTriangulation([1,2,3]))  # 6
    print(s.minScoreTriangulation([3,7,4,5]))  # 144
    print(s.minScoreTriangulation([1,3,1,4,1,5]))  # 13


# =============================================================================
# 补充说明
# =============================================================================
#
# 1) 「固定边 (i, j)，枚举第三个顶点 k」为什么既不会漏、也不会重？
#    * 不会漏：任何剖分方案里，边 (i, j) 一定属于某个三角形（三角形的边不是多边形的边
#      就是对角线，而 (i, j) 正是这块子多边形的边界边）。设它的第三个顶点是 k，
#      由于顶点按顺序排列，k 必然落在 i 与 j 之间，一定被 for 循环枚举到。
#    * 不会重：给定 k，「含边 (i, j) 的那个三角形」就唯一确定了；不同的 k 对应不同的
#      三角形，也就对应互不相同的分解方式。
#    * 为什么能拆成两个独立子问题：三角形 (i, k, j) 把这块多边形切成 i..k 和 k..j
#      两部分，而其它对角线不能穿过这个三角形（对角线两两不相交），
#      所以两边的剖分互不影响，可以各自取最优。
#
# 2) 复杂度：区间共 O(n²) 个，每个区间要枚举 O(n) 个分割点 k，
#    所以时间 O(n³)、空间 O(n²)。这正是「区间 DP」的经典三重循环形状：
#    本质等价于「枚举区间长度 -> 枚举左端点 -> 枚举分割点」，
#    这里写成 i 倒序 + j 正序，效果一样。
#
# 3) 同一套模板还能解决一批题：矩阵链乘、石子合并、戳气球、多边形三角剖分……
#    识别特征都是「一段连续区间（或一条边）+ 枚举一个分割点把区间一分为二」。
#
# 4) 小提示：本题 LeetCode 保证 n >= 3。超出这个范围时两种写法都不可靠，例如
#    n = 1 时写法一的 for 一次都不执行，res 会保持 inf 直接返回；
#    n = 0 时写法二的 f 是空表，`f[0][n-1]` 会下标越界。

