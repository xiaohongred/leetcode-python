from functools import cache


class Solution:
    """
    LeetCode 516. 最长回文子序列

    给定字符串 s，求它的「最长回文子序列」长度。
    子序列不要求连续，只要保持原有前后顺序；回文指正着读、反着读一样。
    例如 "bbbab" -> 4（"bbbb"），"cbbd" -> 2（"bb"）。

    这是一类「区间 DP」：状态不再是「前 i 个字符」，而是「一段区间 s[i..j]」。
    每次只盯着区间的两头 s[i] 和 s[j]，一共就三种情况：
        i > j          ：空区间，长度 0（递归终止）
        i == j         ：只剩一个字符，它自己就是长度 1 的回文
        s[i] == s[j]   ：两头能配对 -> 中间那段的最优解 + 2
        s[i] != s[j]   ：两头不可能同时当回文的两端 -> 丢掉其中一头，取较大者

    两种写法是同一套状态的不同实现：
        写法一 longestPalindromeSubseq    记忆化搜索   dfs(i, j)
        写法二 longestPalindromeSubseqDp  区间表递推   f[i][j]
    """

    def longestPalindromeSubseq(self, s: str) -> int:
        """写法一：记忆化搜索（自顶向下，区间由外向里收缩）。"""
        n = len(s)

        @cache
        def dfs(i, j):
            """
            返回：区间 s[i..j] 的「最长回文子序列」长度。

            i：区间左端点
            j：区间右端点
            """
            if i > j:
                # 空区间，没有字符可用，长度 0。
                # 这条必须放在最前面：当 s[i] == s[j] 且 j == i+1 时，
                # 下一层会调到 dfs(i+1, i)，也就是左右端点「交叉」的区间，
                # 必须先在空区间这里拦住，否则就会越界／算错。
                return 0

            if i == j:
                # 区间里只剩一个字符，它自己就是长度 1 的回文
                return 1

            if s[i] == s[j]:
                # 两头字符相同，让它们充当回文的两端一定不亏，
                # 于是把中间那段 s[i+1..j-1] 的最优解接在它俩内部，长度 +2。
                # （为什么不必再和「只留一头」的情况取 max？见文件末尾说明。）
                return dfs(i+1, j-1) + 2

            # s[i] != s[j]：这两个字符不可能同时作为回文子序列的两端
            # （回文的两端必须相同），所以最长回文子序列要么完全落在
            # s[i+1..j]（不用 s[i]），要么完全落在 s[i..j-1]（不用 s[j]），取较大者。
            return max(dfs(i+1, j), dfs(i, j-1))

        return dfs(0, n-1)

    def longestPalindromeSubseqDp(self, s: str) -> int:
        """
        写法二：区间表递推（自底向上）。

        与写法一的对应关系：f[i][j] <==> dfs(i, j)，一一对应。
        """
        n = len(s)

        # f[i][j]：区间 s[i..j] 的最长回文子序列长度（只用到 i <= j 的上三角）。
        # 整体初始化为 0，于是下三角（i > j）恒为 0 —— 这正好等价于 dfs 里那句
        # `if i > j: return 0`（空区间），所以边界不用单独再写一遍。
        f = [[0]*n for _ in range(n)]

        # ★ 遍历顺序：i 从右往左（n-1 -> 0），j 从左往右（i+1 -> n-1）。
        #   f[i][j] 一共会用到三格，这个顺序保证它们都已经被填好：
        #       f[i+1][j-1]  —— 下一行、更靠左（i 是倒着扫的，下一行早已算完）
        #       f[i+1][j]    —— 下一行、同一列（同上）
        #       f[i][j-1]    —— 本行、更靠左（j 是正着扫的，左边先算）
        for i in range(n-1, -1, -1):
            f[i][i] = 1   # 对角线：单字符区间，长度 1（对应 dfs 的 i == j）
            for j in range(i+1, n):
                if s[i] == s[j]:
                    f[i][j] = f[i+1][j-1] + 2             # 两头配对，中间那段 +2
                else:
                    f[i][j] = max(f[i+1][j], f[i][j-1])   # 丢掉一头，取较大者

        return f[0][n-1]  # 整个串 s[0..n-1] 的答案


if __name__ == "__main__":
    s = Solution()
    print(s.longestPalindromeSubseq("bbbab"))  # 4
    print(s.longestPalindromeSubseq("cbbd"))   # 2


