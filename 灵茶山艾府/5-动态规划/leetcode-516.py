#
# 1) 为什么 s[i] == s[j] 时可以直接 +2，不用再和「丢掉一头」取 max？
#    设 P 是 s[i..j] 的某一个最长回文子序列，按它用到哪几个端点分三种情况：
#      * P 同时用到 s[i] 和 s[j]：由于它俩分别是区间里最左、最右的位置，
#        在 P 里必然就是首尾两个字符，于是 P = s[i] +（中间段）+ s[j]，
#        而中间段是 s[i+1..j-1] 的子序列 —— 所以 |P| <= LPS(i+1, j-1) + 2；
#      * P 没用 s[i]：那 P 整个落在 s[i+1..j] 里。区间里多一个字符，
#        最长回文子序列最多只能长 1，所以 |P| <= LPS(i+1, j-1) + 1 < LPS(i+1, j-1) + 2；
#      * P 没用 s[j]：同理。
#    三种情况下都有 |P| <= LPS(i+1, j-1) + 2；而这个上界显然能达到
#    （把 s[i]、s[j] 直接套在中间段最优解的两端即可），所以取等号。
#
# 2) 复杂度：区间共有 O(n²) 个，每个状态 O(1) 转移 —— 时间 O(n²)；
#    空间同样是 O(n²)（写法一是记忆化缓存的规模，写法二是这张表）。
#    写法二还可以用 1143 题里那个 prev 技巧只保留「下一行」，把空间压到 O(n)。
#
# 3) 这题还有一个等价做法：最长回文子序列 = s 与「反转后的 s」的最长公共子序列，
#    也就是可以直接套 1143 题（LCS）的模板。区间 DP 不用构造反串，更直接一点。
#
# 4) 小提示：写法一能正确处理空串（dfs(0, -1) 会落到空区间返回 0），
#    而写法二在 n = 0 时会在 `return f[0][n-1]` 处下标越界（f 是空表）。
#    LeetCode 保证 s 长度至少为 1，所以不影响判题。

