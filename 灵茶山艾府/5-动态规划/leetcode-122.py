from functools import cache


class Solution:
    """
    LeetCode 122. 买卖股票的最佳时机 II（可以无限次交易）

    给定每天的价格 prices，可以任意选择买入和卖出的日子，交易次数不限，
    但同一时刻最多只能持有一股（必须先卖掉才能再买）。求能获得的最大利润。
    例如 [7,1,5,3,6,4] -> 7（1 买 5 卖赚 4，3 买 6 卖赚 3）。

    ── 状态机视角 ─────────────────────────────────────────────────────
    每天收盘时只有两种状态：
        0 / False：空仓（手里没有股票）
        1 / True ：持仓（手里有股票）
    每天允许的转移就这么几条：
        空仓 -> 持仓：买入，利润 -prices[i]
        持仓 -> 空仓：卖出，利润 +prices[i]
        另外还有两条「什么都不做」的自环：空仓 -> 空仓、持仓 -> 持仓
    于是问题变成：从第 0 天走到最后一天、最终停在空仓的最大收益路径。

    三种写法是同一套状态的不同实现，看懂一个就都会了：
        写法一 maxProfit           记忆化搜索   dfs(i, hold)
        写法二 maxProfitDp         二维递推     f[i][0/1]
        写法三 maxProfitDpSaveMem  变量滚动     prev_0 / prev_1
    """

    def maxProfit(self, prices: list[int]) -> int:
        """写法一：记忆化搜索（自顶向下，从最后一天往前推）。"""
        n = len(prices)

        @cache
        def dfs(i, hold):
            """
            返回：只考虑 prices[0..i] 这些天，把它们全部处理完之后，
                  「手里是否持有股票」为 hold 时能获得的最大利润。

            i   ：当前考虑到的天数（从 n-1 开始往前推）
            hold：True 表示第 i 天结束时手里持有股票，False 表示空仓
            """
            if i < 0:
                # 一天都还没考虑：空仓是最自然的状态，利润 0；
                # 而此刻「持有股票」根本不存在，用 -inf 表示「不可达」。
                # 注意不能用 0 代替：那等于凭空送你一笔免费持仓，会算出偏大的答案。
                return float('-inf') if hold else 0

            if hold:
                # 第 i 天结束时是持仓，两种情况取较大者：
                #   * 第 i 天什么都不做：昨天就已经持仓 -> dfs(i-1, True)
                #   * 第 i 天买入      ：昨天必须空仓，买入要掏钱 -> dfs(i-1, False) - prices[i]
                return max(dfs(i-1, True), dfs(i-1, False) - prices[i])
            # 第 i 天结束时是空仓，两种情况取较大者：
            #   * 第 i 天什么都不做：昨天就空仓 -> dfs(i-1, False)
            #   * 第 i 天卖出      ：昨天必须持仓，卖掉收钱 -> dfs(i-1, True) + prices[i]
            return max(dfs(i-1, False), dfs(i-1, True) + prices[i])

        # 最后一天收盘时还留着股票毫无意义（等于白白多付一次买入的钱），
        # 所以答案取「空仓」这个状态
        return dfs(n-1, False)

    def maxProfitDp(self, prices: list[int]) -> int:
        """
        写法二：二维递推（自底向上）。

        与写法一的对应关系：f[i][hold] <==> dfs(i - 1, hold)。
        （dfs 用下标 -1 表示「一天都还没考虑」，表里用第 0 行表示。）
        """
        n = len(prices)

        # f[i][0]：只考虑前 i 天（prices[0..i-1]）时，收盘空仓能获得的最大利润
        # f[i][1]：只考虑前 i 天时，收盘持仓能获得的最大利润
        f = [[0]*2 for _ in range(n+1)]
        # 边界（对应 dfs 里 i < 0 那行）：还没考虑任何一天时，
        # 空仓利润为 0；持仓是不可能的状态，记 -inf
        f[0][1] = float('-inf')

        for i, p in enumerate(prices):   # p = prices[i]，用第 i 行推出第 i+1 行
            # 第 i+1 天收盘空仓：要么昨天就空仓；要么昨天持仓、今天卖掉（+p）
            f[i+1][0] = max(f[i][0], f[i][1] + p)
            # 第 i+1 天收盘持仓：要么昨天就持仓；要么昨天空仓、今天买入（-p）
            f[i+1][1] = max(f[i][1], f[i][0] - p)

        # 答案：用完全部 n 天、收盘空仓时的最大利润
        return f[n][0]

    def maxProfitDpSaveMem(self, prices: list[int]) -> int:
        """
        写法三：两个变量滚动（在写法二基础上压掉「天数」这一维）。

        算 f[i+1][*] 只用到 f[i][*]，也就是「昨天」的两个值，
        所以每天只要记住两个变量即可，空间由 O(n) 降到 O(1)。
        """
        n = len(prices)  # 下面直接遍历 prices，n 用不到，留着只为和上面两种写法对照

        # prev_0 / prev_1 就是 f[i][0] / f[i][1]；初值对应 f[0]：
        # 空仓利润 0，持仓不可达（-inf）
        prev_0 = 0
        prev_1 = float('-inf')

        for i, p in enumerate(prices):
            # ★ 关键细节：下面两行右边读到的都是「旧的」prev_0 / prev_1（也就是 f[i][*]），
            #   curr_0 / curr_1 相当于新的一行 f[i+1][*]，算齐之后才一起赋回 prev_*。
            #   不能写成「先 prev_0 = ...，再 prev_1 = max(prev_1, prev_0 - p)」那种顺序赋值，
            #   否则第二个式子读到的就是刚更新完的 f[i+1][0] 了。
            #   （本题恰好有个巧合：卖出和买入用的都是同一个 p，多出来的那个候选值
            #     永远不会更优，所以顺序赋值的结果碰巧也一样；但别依赖这个巧合，
            #     「先把新值算齐再统一赋值」才是滚动数组更稳妥、也更好迁移的写法。）
            curr_0 = max(prev_0, prev_1 + p)
            curr_1 = max(prev_1, prev_0 - p)
            prev_0, prev_1 = curr_0, curr_1

        return prev_0


# =============================================================================
# 补充说明
# =============================================================================
#
# 1) 为什么「不可达」要用 -inf 而不是 0？
#    0 会被 max 当成一个合法可达值，于是「凭空多出一笔持仓」这种情况会被算进最优解，
#    相当于允许你卖了再买却不花钱。用 -inf 表示不可达，参与 max 时自然被淘汰。
#    （这一点在写法一里就是 `return float('-inf') if hold else 0` 那一行。）
#
# 2) 为什么答案只取空仓状态（dfs(n-1, False) / f[n][0]）？
#    最后还持仓，等于白白多付了一次买入的钱；把「最后一次买入」这一步删掉
#    不会破坏任何已有交易，而利润只增不减（价格非负）。所以最优解一定空仓收尾。
#
# 3) 本题（交易次数不限）还有一个很直观的等价结论：
#        答案 = Σ max(0, prices[i] - prices[i-1])
#    也就是把所有「上涨段」全部吃满。可以用它快速自检 DP 的结果。
#
# 4) 「持仓 / 空仓」这个状态机是个通用模板，变体只是在它上面加状态：
#    LeetCode 121（最多买一次）：再加一维表示「还没买过」，买入只能从未交易状态来；
#    LeetCode 309（卖出后冷冻一天）：再加一个「冷冻」状态；
#    LeetCode 714（卖出需付手续费）：卖出时把手续费一并减掉。
