from functools import cache


# =============================================================================
# 参考实现：完全背包（每种物品可以选「任意多次」）
#
# 和 0-1 背包（每种物品最多选一次）相比，代码只差一个地方：
#   选完 weights[i] 之后，还能不能再选一次它？
#     * 0-1 背包：不能  -> 递归到 dfs(i - 1, ...)
#     * 完全背包：可以  -> 递归到 dfs(i, ...)   （i 不往前退，所以还能再拿第 i 件）
# =============================================================================


def unbounded_knapsack_dfs(weights, values, capacity):
    """写法一：记忆化搜索（自顶向下）。"""
    n = len(weights)

    @cache
    def dfs(i, c):
        """
        返回：从 weights[0..i] 这些物品中挑若干个（每件可以挑任意多次），
              在总重量不超过 c 的前提下能获得的最大总价值。

        i：当前允许使用的物品下标上限（即只考虑 weights[0..i]）
        c：当前还剩多少容量
        """
        if i < 0:
            # 没有物品可选了，价值只能是 0
            return 0
        if weights[i] > c:
            # 第 i 件物品单件就超重，装不下，只能不选它
            return dfs(i - 1, c)
        # 两种选择取较大值：
        #   不选第 i 件：回去考虑 i-1，容量不变
        #   选  第 i 件：容量减去 weights[i]、价值加上 values[i]，
        #                ★ 注意仍然是 dfs(i, ...) 而不是 dfs(i - 1, ...)，
        #                  因为完全背包允许重复选同一件物品，下标 i 不往前退。
        return max(dfs(i - 1, c), dfs(i, c - weights[i]) + values[i])

    return dfs(n - 1, capacity)


def unbounded_knapsack(weights, values, capacity):
    """写法二：一维数组递推（自底向上），同一个数组滚动更新。"""
    n = len(weights)
    # dp[c]：容量为 c 时能装出的最大价值（初始全 0，表示一件都不装）
    dp = [0] * (capacity + 1)

    for i in range(n):
        # ★ 内层 c 必须「正序」遍历：
        #   dp[c] = max(dp[c], dp[c - weights[i]] + values[i]) 里，
        #   dp[c - weights[i]] 下标更小，正序遍历时它已经被本轮更新过了，
        #   代表的状态是「已经用过第 i 件物品」，于是允许再用一次，
        #   这恰好就是完全背包的语义。
        #   （0-1 背包要的是「本轮更新之前的旧值」，所以那边必须倒序遍历。）
        for w in range(weights[i], capacity + 1):
            dp[w] = max(dp[w], dp[w - weights[i]] + values[i])

    return dp[capacity]


class Solution:
    """
    LeetCode 322. 零钱兑换

    给定若干种硬币面额 coins（每种可以用任意多枚）和目标金额 amount，
    求凑出 amount 所需的「最少硬币枚数」；若凑不出则返回 -1。

    这就是「完全背包求最小值」：
        物品的重量 = 硬币面额，物品的价值 = 1（每用一枚硬币，枚数 +1），
        背包容量 = amount，问的是「恰好凑出 amount」时价值的最小值。

    和文件顶部「求最大价值」的完全背包相比，只有两处不同：
        1) max 换成 min；
        2) 必须能区分「凑不出」：用 +∞（float('inf')）表示不可达，
           最后若仍是 +∞ 就返回 -1。
           （求最大值时用 0 当默认值就够了，因为 0 代表「一件都不装」；
             但这里 0 代表「一枚硬币都不用」，会被误当成合法答案，
             所以要用 +∞ 表示「这个金额凑不出来」。）
    """

    def coinChange(self, coins: list[int], amount: int) -> int:
        """写法一：记忆化搜索（自顶向下）。"""
        n = len(coins)

        @cache
        def dfs(i, c):
            """
            返回：只用 coins[0..i] 这些面额（每种硬币可用任意多枚）凑出金额 c
                  所需的最少硬币枚数；若凑不出则返回 +∞。
            """
            if i < 0:
                # 没有硬币可用了：金额刚好为 0 说明凑成功（用了 0 枚硬币），返回 0；
                # 否则这条路走不通，返回 +∞。
                return 0 if c == 0 else float('inf')
            if c < coins[i]:
                # 当前面额比还需要的金额还大，用它必然超额，只能不选它
                return dfs(i - 1, c)
            # 两种选择取较小值：
            #   不用 coins[i]：可选的种类减少，金额不变
            #   用   coins[i]：金额减去面额、枚数 +1，
            #                  ★ 下标仍是 i（完全背包，同一面额可以接着用）
            return min(dfs(i - 1, c), dfs(i, c - coins[i]) + 1)

        ans = dfs(n - 1, amount)
        # ans 仍是 +∞，说明它一次都没被更新过，即凑不出目标金额
        return ans if ans < float('inf') else -1

    def coinChangeDp(self, coins: list[int], amount: int) -> int:
        """
        写法二：二维表递推（自底向上）。

        对应关系：f[i][c] <==> dfs(i - 1, c)。
        """
        n = len(coins)

        # f[i][c]：只用前 i 种硬币（coins[0..i-1]，每种可用任意多枚）凑出金额 c
        #          所需的最少枚数；+∞ 表示凑不出（不可达）。
        f = [[float('inf')] * (amount + 1) for _ in range(n + 1)]

        # 边界：用「前 0 种硬币」凑出金额 0 —— 一枚都不用，所以是 0 枚。
        # 其余 f[0][c] (c > 0) 保持 +∞：没有任何硬币可用，凑不出正数金额。
        f[0][0] = 0

        for i, x in enumerate(coins):  # x = coins[i]，用「前 i 种」推出「前 i+1 种」
            for c in range(amount + 1):    # c 是「还需要凑出的剩余金额」
                if c < x:
                    # 面额 x 比需要的金额还大，没法用它，只能沿用上一行
                    f[i + 1][c] = f[i][c]
                else:
                    # 不用 x：f[i][c]
                    # 用  x：f[i + 1][c - x] + 1
                    #   ★ 这里是 f[i + 1] 而不是 f[i]！因为完全背包允许再用一次 x，
                    #     「用完之后」仍处在「已经考虑过 x」的这一行里。
                    #     这正是完全背包与 0-1 背包的关键差别（那边写 f[i][c - x]）。
                    f[i + 1][c] = min(f[i][c], f[i + 1][c - x] + 1)
            # ★ 内层 c 必须「正序」递增：
            #   f[i + 1][c] 用到了同一行的 f[i + 1][c - x]，它下标更小，
            #   只有 c 从小到大遍历，这个值才已经在本轮算好了。
            #   （若改成倒序，f[i + 1][c - x] 这一格还没被赋值、仍是初始的 +∞，
            #     「用 x」的分支就永远用不上，算出来会全是凑不出。）
            #   对比：0-1 背包那一行写的是 f[i][c - x]（上一行），正序倒序都不影响结果。

        ans = f[n][amount]
        return ans if ans < float('inf') else -1

    def coinChangeDpSaveMem(self, coins: list[int], amount: int) -> int:
        """
        写法三：一维数组（在写法二的基础上再压掉「硬币种类」这一维）。

        思路：算 f[i+1] 只用到 f[i]，那就让「上一行」和「当前行」共用同一个数组 f，
        一边读一边就地更新。此时 f[c] 的含义随外层循环滚动变化：
            * 进入第 i 轮之前：f[c] = f[i][c]    （只用前 i 种硬币凑出 c 的最少枚数）
            * 第 i 轮结束之后：f[c] = f[i+1][c]  （前 i+1 种硬币凑出 c 的最少枚数）
            * 全部循环结束后：f[c] = f[n][c]，答案就是 f[amount]
        空间由 O(n · amount) 降到 O(amount)。

        注意：这里的 f 和写法一的 dfs、写法二的 f 表格是同一套状态，只是写法不同。
        """
        n = len(coins)  # 本题直接 for x in coins 遍历，n 用不上，留着只为和上面两种写法对照

        # f[c]：用「当前已经考虑过的那些硬币」凑出金额 c 所需的最少枚数；
        #       +∞ 表示这个金额还凑不出（不可达）。
        f = [float('inf')] * (amount + 1)
        f[0] = 0  # 边界：凑出金额 0 一枚都不用，所以是 0 枚；其余全是 +∞

        for x in coins:
            # ★ 内层 c 必须「正序」遍历（从 x 递增到 amount），这是完全背包的标志：
            #   f[c] = min(f[c], f[c - x] + 1) 这一行里两个 f 分工不同 ——
            #     * 等号右边的 f[c]   ：本轮还没写过它，仍是 f[i][c]，
            #                           代表「不用面额 x」这个选择；
            #     * 等号右边的 f[c-x] ：下标更小，正序时已经被本轮更新过，
            #                           代表「已经用过面额 x」，所以可以再用一枚 x。
            #   两者取 min，正是「用 / 不用 x」的比较。
            #   （0-1 背包要的是「本轮更新之前的旧值」，所以那边必须倒序。）
            #
            # 另外，下界取 x 而不是 0，等价于替我们做掉了二维版里那句 `if c < x`：
            #   c < x 时 f[c - x] 没有意义，这些格子干脆不动，
            #   保持原值恰好就等于「这一轮不用面额 x」的结果。
            for c in range(x, amount + 1):
                f[c] = min(f[c], f[c - x] + 1)

        ans = f[amount]
        # ans 仍是 +∞，说明所有面额都试过了也凑不出目标金额
        return ans if ans < float('inf') else -1

# =============================================================================
# 小结：完全背包 vs 0-1 背包
# =============================================================================
#
#                        0-1 背包（每件最多选一次）      完全背包（可重复选）
#   dfs 转移             dfs(i - 1, c - w) + v          dfs(i, c - w) + v
#   二维递推             用 f[i][c - w]                 用 f[i + 1][c - w]
#   一维递推             内层 c 必须「倒序」            内层 c 必须「正序」
#
# 为什么一维的遍历方向刚好相反？
#   一维数组把「上一行」和「当前行」压成同一个数组、就地更新，于是
#   「读到的 f[c - w] 是新值还是旧值」就决定了同一件物品能不能被重复选：
#     * 完全背包想要「新值」（= 本轮已经用过 w，可以再用一次）-> 正序
#     * 0-1 背包想要「旧值」（= w 还没用，保证只用一次）      -> 倒序
#
# 本题（零钱兑换）与文件顶部「求最大价值」的完全背包相比，只多了两件事：
#   * max 换成 min；
#   * 用 +∞ 表示「凑不出」，最后判断是否仍为 +∞ 来决定要不要返回 -1。
#
# 本题三种写法的对应关系（状态含义完全一样，只是存储方式不同）：
#   写法一  coinChange          记忆化搜索    dfs(i, c)
#   写法二  coinChangeDp        二维递推      f[i][c]
#   写法三  coinChangeDpSaveMem 一维滚动      f[c]
#   三者都是在「用 / 不用第 i 种硬币」之间取 min，并把「凑不出」记为 +∞。



if __name__ == "__main__":
    s = Solution()
    print(s.coinChange([1, 2, 5], 11))  # 3
    print(s.coinChange([2], 3))        # -1
    print(s.coinChange([1], 0))        # 0
    print(s.coinChange([1], 1))        # 1
    print(s.coinChange([1], 2))        # 2