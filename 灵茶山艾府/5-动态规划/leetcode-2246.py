# 补充说明
# =============================================================================
#
# 1) 为什么「边遍历边配对」不会漏掉最优解？
#    假设最优路径在 x 处拐弯，用的是两个孩子 y1、y2 的链。无论它们谁先被遍历到，
#    先到的那个一定会把自己那条链的长度存进 x_len；等轮到另一个时，
#    `ans = max(ans, x_len + y_len)` 里的 x_len 已经 >= 先到者的链长，
#    于是这次比较就把「这两条链」的组合考虑到了。
#    也就是说，任意一对合法孩子都会被「先来的进 x_len、后来的负责配对」覆盖一次。
#
# 2) 与 124 题对照着看会更清楚：
#    124 题：返回值 = 单侧链（只能带一条腿往上），ans = 左链 + 自己 + 右链；
#    本题  ：结构完全一样，只是「链长」改用边数计、多一个「字符不同」的判断，
#            孩子数从「最多两个」变成「任意多个」。
#    这也是它被归在「动态规划」目录下的原因：本质是一道树形 DP。
#
# 3) 复杂度：每个节点只被 dfs 访问一次，每条边只被看一次，时间 O(n)；
#    额外空间是 g 的 O(n) 加上递归栈 O(h)（最坏是链状树，O(n)）。
#
# 4) 小提示：本实现假设节点 0 是根（题目保证 parent[0] = -1），
#    建图时从 i = 1 开始也正是基于「只有一个根」这一点。
