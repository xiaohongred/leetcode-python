from typing import List


class Solution:
    """
    LeetCode 2246. 相邻字符不同的最长路径

    给定一棵以 0 为根的树（parent[i] 是节点 i 的父节点，parent[0] = -1）
    和每个节点上的字符 s[i]，求最长的一条路径（用节点个数衡量），
    要求路径上**相邻两个节点的字符不相同**。

    思路是树形 DP，和 124 题（二叉树最大路径和）是同一个套路：
        * dfs(x) 的【返回值】：从 x 往下、只朝【一侧】延伸的合法链的长度；
          它是还要交给父节点继续拼的半成品（父节点只能接住一侧）。
        * 全局 ans：允许路径在某个节点处「拐弯」，把两个孩子的最长合法链
          通过 x 接起来。
    区别只在于：这里多了一个「相邻字符不同」的判断，而且链长用**边数**来数。

    ★ 为什么用「边数」而不是「节点数」？
      因为拼接两条链时是 `x_len + y_len`（一边贡献一节），用边数相加最自然；
      最后再 +1 换成题目要的节点数即可 —— 一条路径的「节点数 = 边数 + 1」。
    """

    def longestPath(self, parent: List[int], s: str) -> int:
        n = len(parent)

        # g[x] 存 x 的所有孩子：把「父指针数组」转成「邻接表」，方便从根往下递归
        g = [[] for _ in range(n)]
        # 从 i = 1 开始：节点 0 是根，它的 parent 是 -1，本来就没有父节点要挂
        for i in range(1, n):
            g[parent[i]].append(i)

        ans = 0  # 用边数记答案，所以初值 0 就代表「至少 1 个节点」

        def dfs(x):
            """
            返回：从 x 出发、只朝一个方向往下走的「合法链」的最大边数
                  （合法 = 沿途每条边两端的字符都不同）。

            顺带更新全局 ans：以 x 为最高点、把两条子链接起来的路径。
            """
            nonlocal ans
            x_len = 0          # 到目前为止，x 的孩子里能接出来的最长合法子链（边数）
            for y in g[x]:     # 依次考察每个孩子
                # ★ 先递归，不管字符是否相同！
                #   s[y] == s[x] 只说明「y 那条链不能接到 x 上」，
                #   但 y 的子树内部完全可能藏着更长的答案，所以必须照样往下算。
                y_len = dfs(y) + 1      # 从 y 往下最优链的边数，再加上 x->y 这一条边

                if s[y] != s[x]:        # 这条边合法，才能把 y 的链接到 x 上
                    # 把「之前遇到的最长子链」和「y 这条」拼成一条经过 x 的路径。
                    # 注意这里用的 x_len 还是旧值，所以它一定来自另一个孩子，
                    # 不会把同一个孩子的链重复用两次。
                    ans = max(ans, x_len + y_len)
                    # 再把 y 这条也纳入「目前为止最好」的候选，供后面的孩子配对
                    x_len = max(x_len, y_len)

            return x_len        # 只能带一条链往上传给父节点

        dfs(0)                  # 从根开始
        return ans + 1          # ans 记的是边数，节点数 = 边数 + 1


if __name__ == "__main__":
    s = Solution()
    parent = [-1,0,0,1,1,2]
    s_str = "abacbe"
    print(s.longestPath(parent, s_str))  # 3


