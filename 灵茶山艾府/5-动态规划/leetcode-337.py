# 补充说明
# =============================================================================
#
# 1) 为什么「偷 / 不偷」一个 bit 的状态就够了？
#    因为约束只发生在「父子相邻」这一层：偷了 node 只影响它的直接孩子，
#    不影响孙节点（孙节点照样可以偷）。所以站在 node 的视角，
#    只要知道「node 偷不偷」，孩子的可选范围就完全确定了。
#
# 2) 两个转移为什么一个用「不偷」、一个用 max？
#      * 偷 node   -> 孩子被强制禁止 -> 只能用 l_not_rob / r_not_rob，没有余地；
#      * 不偷 node -> 孩子解除禁令   -> 偷或不偷都行，择优即可 -> max(...)。
#
# 3) 复杂度：每个节点只访问一次，时间 O(n)；额外空间是递归栈，深度为树高 h，
#    最坏（链状树）O(n)。返回二维组并不改变量级。
#
# 4) 同一套「树形 DP + 二元状态」的模板也常见于：树的染色（相邻不同色）、
#    树上最大权独立集等 —— 识别特征就是「父节点的选择会限制子节点的选择，
#    而且只限制一层」。
