# Definition for a binary tree node.
class TreeNode:
    def __init__(self, val=0, left=None, right=None):
        self.val = val
        self.left = left
        self.right = right


class Solution:
    """
    LeetCode 337. 打家劫舍 III（树形 DP）

    小偷盯上了一片二叉树形状的街区，每个节点是一间房子、值是金额。
    规则：**偷了某个节点，就不能偷它的直接子节点**（父子相邻会报警），
    但孙节点及以下不受这条限制。求能偷到的最大金额。
    例如 [3,2,3,null,3,null,1] -> 7，[3,4,5,1,3,null,1] -> 9。

    这跟 198 题（打家劫舍，数组版）是同一个模型，只是结构从「一条链」变成「一棵树」：
        * 数组版：不能偷相邻的两个位置；
        * 本题  ：不能同时偷父节点和子节点。
    状态还是那一个 bit：**当前节点偷 / 不偷**。因为它恰好决定了子节点还能不能偷。

    ★ 核心设计：dfs(node) 一次返回【两个数】，而不是只返回一个。
      因为父节点做决策时需要知道「子节点偷不偷」两种情况各自的最优值：
          * 父节点要偷   -> 子节点一定不能偷 -> 需要子节点的「不偷」值；
          * 父节点不偷   -> 子节点偷不偷都行 -> 需要子节点两个值里的较大者。
      只返回一个数是给不出这些信息的。
      （对比 124 题、2246 题：那类题父节点只要「最佳单侧链」一个数就够，
        所以那两题的 dfs 只返回一个值。）
    """

    def rob(self, root: TreeNode | None) -> int:
        def dfs(node):
            """
            返回二维组 (rob, not_rob)，都表示「以 node 为根的子树」能偷到的最大金额：
                rob     ：在【偷 node】的前提下，子树能偷到的最大值；
                not_rob ：在【不偷 node】的前提下，子树能偷到的最大值。
            """
            if node is None:
                # 空节点：偷不偷都是 0，两个值一样
                return 0, 0

            # 先递归拿到左右子树的两套值（后序遍历：先算孩子，再算自己）
            l_rob, l_not_rob = dfs(node.left)
            r_rob, r_not_rob = dfs(node.right)

            # 【偷 node】：父子不能同时偷，所以左右孩子必须都处于「不偷」状态，
            # 只能各取它们的 not_rob，再加上 node 自己的金额。
            # 注意这里绝不能对「孩子偷不偷」取 max —— 偷了 node 就没有选择余地了。
            rob = l_not_rob + r_not_rob + node.val

            # 【不偷 node】：孩子身上的禁令解除，偷或不偷都可以；
            # 左右子树互相独立，所以各自取 max 之后再相加。
            not_rob = max(l_rob, l_not_rob) + max(r_rob, r_not_rob)

            return rob, not_rob

        # 根节点偷不偷都允许，取两个状态里较大的那个。
        # 注意这里不需要像 124 题那样维护全局 ans：
        # 因为每个节点的两种状态都被完整返回上来了，答案自然就落在根上。
        return max(dfs(root))


if __name__ == "__main__":
    s = Solution()
    # [3,2,3,null,3,null,1] -> 7：偷根节点 3，再偷两个孙节点 3 和 1
    print(s.rob(TreeNode(3, TreeNode(2, None, TreeNode(3)),
                            TreeNode(3, None, TreeNode(1)))))  # 7
    # [3,4,5,1,3,null,1] -> 9：不偷根 3，改偷两个孩子 4 和 5，更划算
    print(s.rob(TreeNode(3, TreeNode(4, TreeNode(1), TreeNode(3)),
                            TreeNode(5, None, TreeNode(1)))))  # 9
    # 只有一个节点：直接偷它
    print(s.rob(TreeNode(5)))  # 5


