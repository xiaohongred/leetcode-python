class Solution:
    """
    LeetCode 739. 每日温度

    给定每日气温 temperatures，对每一天求出「还要再等多少天，才会出现更高的温度」；
    若之后都不会更高，则该天填 0。
    例如 [73, 74, 75, 71, 69, 72, 76, 73] -> [1, 1, 4, 2, 1, 1, 0, 0]

    两个方法都是「单调栈」，区别只在扫描方向：
        * dailyTemperatures   从右往左扫：随时维护「右边还有哪些候选」，
                              每个位置当场就能算出自己的答案。
        * dailyTemperaturesV2 从左往右扫：栈里存「还没结算的日子」，
                              等到更暖的天出现时，再回头给它们结算（延迟结算）。

    注意题目要的是「更高」，所以是严格大于：温度相同的日子不算
    （例如 [73, 73] 的答案是 [0, 0]）。

    两个实现都是 O(n)：每个下标最多进栈一次、出栈一次，额外空间 O(n)。
    """

    def dailyTemperatures(self, temperatures: list[int]) -> list[int]:
        """写法一：从右往左扫，栈里维护「右边仍然可能是答案的候选下标」。"""
        n = len(temperatures)
        ans = [0] * n

        # st 存下标，并始终保持这样的不变量：
        #   * 从栈底到栈顶，下标越来越小 —— 也就是位置越来越靠左、离当前的 i 越来越近；
        #   * 从栈底到栈顶，温度严格递减 —— 栈顶是这些候选里温度最低的。
        # 于是 st[-1] 就是「离 i 最近、且温度还可能高于 i」的那个候选。
        st = []

        for i in range(n-1, -1, -1):
            t = temperatures[i]

            # 把温度 <= t 的候选全部弹掉。
            # 为什么可以放心弹掉？设被弹掉的是下标 j（j > i，在 i 右边）。
            # 对 i 左边的任意位置 p（p < i < j）：如果 j 曾经可能是 p 的答案，
            # 那么 temperatures[i] >= temperatures[j] > temperatures[p]，
            # 而且 i 离 p 更近，所以 p 的答案应该取 i，j 再也不可能被选上 ——
            # 换句话说，j 被 i「挡住了」。
            while st and t >= temperatures[st[-1]]:
                st.pop()

            # 弹完之后，栈顶若存在，就是「右边第一个比 t 更高的温度」所在的下标：
            #   * 它比 t 高：经过上面的 while，栈里剩下的温度全都 > t，满足题目要求；
            #   * 它离 i 最近：设 j* 是 i 右边第一个比 t 高的位置。
            #     先证 j* 一定还在栈里 —— 若它早先被弹掉，说明存在 p 满足 i < p < j*
            #     且 temperatures[p] >= temperatures[j*] > t，那 p 才是「第一个更高的」，
            #     与 j* 的定义矛盾。
            #     再看栈顶：j* 上面的元素下标都落在 (i, j*) 之间，由 j* 的最小性，
            #     它们的温度不可能 > t，而栈里剩下的温度又都 > t，故 j* 只能是栈顶。
            if st:
                ans[i] = st[-1] - i

            # 自己也要入栈：它可能是左边某些位置的答案（ans[i] 若没被赋值，
            # 保持初始的 0，正好表示「右边没有更高的温度」）
            st.append(i)
        return ans

    def dailyTemperaturesV2(self, temperatures: list[int]) -> list[int]:
        """写法二：从左往右扫，栈里存「还没等到更高温度的日子」，遇到更暖的天再回头结算。"""
        n = len(temperatures)
        ans = [0] * n

        # st 里存的是「已经扫过、但还没有遇到更高温度」的下标，始终保持：
        #   * 从栈底到栈顶，下标递增 —— 栈顶是最近扫过的那天，离「现在」最近；
        #   * 从栈底到栈顶，温度严格递减。
        st = []

        for i, t in enumerate(temperatures):
            # 今天的温度 t 比栈顶那天更高，说明「栈顶那天」等的就是今天，
            # 它的答案就是 i - 栈顶下标。
            # 这里必须用严格大于：温度相同不算「更高」。
            # while 可能连续结算好几天 —— t 可能同时高于栈里好几个日子，
            # 而它们全都是在今天第一次等到更高的温度。
            while st and t > temperatures[st[-1]]:
                j = st.pop()
                ans[j] = i - j  # 中间隔了多少天
            # 今天也还没等到更高的温度，先入栈等着
            st.append(i)
        return ans


if __name__ == "__main__":
    s = Solution()
    print(s.dailyTemperatures([73, 74, 75, 71, 69, 72, 76, 73]))  # [1,1,4,2,1,1,0,0]
    print(s.dailyTemperatures([30, 40, 50, 60]))                  # [1,1,1,0]
    print(s.dailyTemperatures([30, 60, 90]))                      # [1,1,0]


# =============================================================================
# 两种方向的对比
# =============================================================================
#
#                     写法一（从右往左）                  写法二（从左往右）
#   栈的含义        i 右边「仍可能当答案」的候选            扫过的、还没结算的下标
#   栈内温度        从栈底到栈顶严格递减                    从栈底到栈顶严格递减
#   栈内下标        从栈底到栈顶递减（栈顶离 i 最近）        从栈底到栈顶递增（栈顶离现在最近）
#   出答案的时机    当场算出 ans[i]                         将来遇到更暖的天时回头结算
#   弹栈触发条件    新来的 t 把「不高于自己」的候选挤掉      新来的 t 给「低于自己」的下标结算
#
# 两个版本的弹栈写法看着不同（>= 与 >），描述的其实是同一件事：
# 都在找「右边第一个严格大于自己」的位置，只是观察角度反过来了。
# 两者都是 O(n)：每个下标最多进栈一次、出栈一次。
