class Solution:
    """
    LeetCode 42. 接雨水

    给定一排宽度为 1 的柱子高度 height，求下雨后一共能接住多少单位的雨水。
    例如 [0,1,0,2,1,0,1,3,2,1,2,1] -> 6，[4,2,0,3,2,5] -> 9。

    这里用「单调递减栈」：栈里存下标，对应高度从栈底到栈顶严格递减。
    遍历到柱子 i（高 h）时，如果 h 不低于栈顶柱子，就说明栈顶那根柱子被
    「右墙 h」夹住了，它可以充当某个水洼的「底部」，于是弹出它并结算这一层水：

        左墙 = 弹出之后新的栈顶（它比底部高，是底部左边离它最近的更高柱子）
        右墙 = 当前下标 i
        水深 = min(左墙高, 右墙高) - 底部高      （水面高度由两面矮墙决定）
        宽度 = i - 左墙下标 - 1                 （两墙之间、不含两墙的柱子数）

    同一个 i 可能一口气夹住栈里好几层（while 循环），所以水是「从低到高一层层
    往上叠」加出来的，合起来正好等于每根柱子上方 min(左最高, 右最高) - 自身高。

    时间 O(n)、空间 O(n)：每个下标最多进栈一次、出栈一次。
    """

    def trap(self, height: list[int]) -> int:
        ans = 0

        # st 存下标，始终保持不变量：从栈底到栈顶，高度严格递减。
        # 也就是说，栈里留着的都是「右边还没出现过不低于自己的柱子」的那些柱子。
        st = []

        for i, h in enumerate(height):
            # 当前柱子 h 是栈顶柱子的「右墙」。只要 h 不低于栈顶，栈顶就被左右夹住了，
            # 立刻弹出它并按「它作为底部」结算一层水。
            # （这里用 >= 而不是 >：等高时也会弹掉，那种情况下算出的水深恰好是 0，
            #   不影响答案；两种写法都正确。）
            while st and h >= height[st[-1]]:
                bottom_h = height[st.pop()]  # 被弹出的是「水洼底部」，记下它的高度
                if len(st) == 0:
                    # 弹出后栈空了：这个底部左边没有任何柱子可以当左墙，
                    # 它上方存不住水。（此时 while 条件其实也不成立，
                    # 这里 break 是为了不去读 st[-1]，顺便明确表达「没有左墙」。）
                    break
                left = st[-1]  # 新的栈顶就是左墙
                # 为什么它一定是「底部左边最近的更高柱子」？因为底部当初压栈时，
                # 所有不高于它的柱子都被弹走了，所以它下方的元素全都比它高，
                # 且它下面紧挨的那个就是离它最近的那个。
                dh = min(height[left], h) - bottom_h  # 这一层的水深（水面 - 底部）
                ans += dh * (i - left - 1)            # 宽度为两墙之间的柱子数，每根宽 1
            # 当前柱子入栈，成为后面柱子的候选左墙
            st.append(i)
        return ans


if __name__ == "__main__":
    s = Solution()
    print(s.trap([0,1,0,2,1,0,1,3,2,1,2,1]))  # 6
    print(s.trap([4,2,0,3,2,5]))              # 9


# =============================================================================
# 走一遍 [4, 2, 0, 3, 2, 5]（答案 9），看水是怎么一层层加出来的
# =============================================================================
#
#   i=3, h=3: 弹出 2（底高 0），左墙 1（高 2），水深 min(2,3)-0 = 2，宽度 1  ->  ans = 2
#             弹出 1（底高 2），左墙 0（高 4），水深 min(4,3)-2 = 1，宽度 2  ->  ans = 4
#   i=5, h=5: 弹出 4（底高 2），左墙 3（高 3），水深 min(3,5)-2 = 1，宽度 1  ->  ans = 5
#             弹出 3（底高 3），左墙 0（高 4），水深 min(4,5)-3 = 1，宽度 4  ->  ans = 9
#             弹出 0（底高 4），栈空 -> 左边没有墙，break
#
# 注意 i=3 那一步连着弹了两次，说明「同一根右墙」可以夹住好几层：
#   下标 2 那根柱子上方的水被拆成两段算 —— 先算高度 0~2（宽度 1），再算高度 2~3（宽度 2），
#   合起来是高度 0~3，正好等于 min(左最高 4, 右 3) - 自身高 0 = 3。
#   换句话说，弹出的顺序是「从低到高」，水位一层层往上涨，这就是 while 循环的意义。
#
# 另外一点：本题还有 O(1) 空间的「双指针」解法（左右各维护一个最大高度，
# 每次从较矮的一侧向内收缩），空间更优；而单调栈这个写法更容易和
# 「每日温度」「柱状图中最大的矩形」这类题串起来。
