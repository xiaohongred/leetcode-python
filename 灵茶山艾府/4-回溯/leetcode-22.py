class Solution:
    def generateParenthesis(self, n: int) -> list[str]:
        """
        生成 n 对括号的所有合法组合。

        例如 n = 3 时返回：
        ['((()))', '(()())', '(())()', '()(())', '()()()']

        这属于「位置型回溯」：按位置从左到右依次填空，每个位置尝试放 '(' 或 ')'，
        并用两个约束保证「任意前缀中左括号数 >= 右括号数」。
        结果总数正好是卡塔兰数 C(2n, n) / (n + 1)。
        """
        # 结果串总长度固定为 2n
        m = 2 * n

        # 保存所有合法组合
        ans = []
        # 长度固定为 m 的字符数组，用「下标赋值」而不是 append / pop
        path = [''] * m

        def dfs(i: int, open: int) -> None:
            """
            i：下一个要填的位置下标，即前 i 个位置已经填好
            open：已经放置的左括号 '(' 的数量

            关键转换：前 i 个位置里，既然有 open 个 '('，
            那么已经放置的右括号 ')' 数量就是 **i - open**。
            （可读性上也可以先写 close = i - open，本代码直接用 i - open）
            """
            # 终点：2n 个位置全部填满
            # 注意这里不需要校验合法性 —— 见文件末尾注释的「终点不变量」说明
            if i == m:
                ans.append(''.join(path))
                return

            # ---------- 约束一：还能不能放左括号 ----------
            # 左括号一共只有 n 个，所以只有 open < n 时才能再放一个 '('。
            # 这是「总数上限」的剪枝：已经用完 n 个 '(' 就封死这条分支。
            if open < n:
                path[i] = '('
                # 放置后左括号数量 +1，位置前进一格
                dfs(i + 1, open + 1)

            # ---------- 约束二：还能不能放右括号 ----------
            # 合法性要求：任何前缀中「左括号数 >= 右括号数」。
            # 现在已放左括号 open 个、右括号 i - open 个：
            #   * 若 i - open == open（两者相等），此时再放一个 ')' 就会让
            #     右括号数超过左括号数，该前缀失配，整个串必然非法；
            #   * 只有 i - open < open（左括号更多）时，才允许再放 ')'。
            # 所以条件写成 i - open < open，这是「前缀平衡」的剪枝。
            #
            # 例：i = 3, open = 2 时，已放右括号 1 个，1 < 2 成立，可以放 ')'
            #     例：i = 4, open = 2 时，已放右括号 2 个，2 < 2 不成立，
            #         说明当前是 "()()" 这种平衡态，再放 ')' 就非法，直接跳过。
            if i - open < open:
                path[i] = ')'
                # 放置右括号不改变 open，只前进一格
                dfs(i + 1, open)

            # 小提醒：两个 if 是「并列」关系，互不排斥。
            # 当两个条件同时成立时，这个位置既可以是 '(' 也可以是 ')'，
            # 这正是分叉的来源；而当两个都不成立时，该分支自然结束（相当于剪枝）。

        # 从位置 0 开始，此时左括号数量为 0
        dfs(0, 0)
        return ans


if __name__ == "__main__":
    s = Solution()
    n = 3
    result = s.generateParenthesis(n)
    print(result)  # 输出所有有效的括号组合


# =============================================================================
# 补充：两个容易疑惑的点
# =============================================================================
#
# 1) 为什么不需要显式回滚（没有 pop）？
#    因为 path 是固定长度的数组，用 path[i] = 字符 覆盖写入。
#    同一层的两个分支写的是同一个下标 i，后写会覆盖先写；
#    而读取只发生在 i == m 时，那时每个位置都已被本次路径填满，
#    所以不存在读到上个分支残留字符的问题。
#
# 2) 终点不变量：走到 i == m 时，必然 open == n，串一定合法。
#    理由：约束一保证 open <= n；
#          约束二保证任意时刻「右括号数 <= 左括号数」，即 2n - open <= open，
#          由 2n - open <= open 得 open >= n。
#    两式夹逼得 open == n，于是右括号数 = 2n - n = n，恰好 n 对，必然合法。
#    实测 n = 0..7，终点处 open 恒等于 n。