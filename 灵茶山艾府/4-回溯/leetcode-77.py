class Solution:
    def combine(self, n: int, k: int) -> list[list[int]]:
        """
        返回 1..n 中所有长度为 k 的组合（不考虑顺序）。

        例如 n = 4, k = 2 时返回：
        [[4, 3], [4, 2], [4, 1], [3, 2], [3, 1], [2, 1]]

        这属于「组合型回溯」：从大到小依次选择数字，选过的数字不再重复使用，
        并且通过「剪枝」提前砍掉不可能凑齐 k 个数字的分支。
        """
        # 保存所有完整的组合
        ans = []
        # 当前正在构建的组合；也可以写成 path = [0] * k 用下标赋值，
        # 那样就不需要 append / pop，但递归参数要额外带上当前长度
        path = []

        def dfs(i: int) -> None:
            """
            i 表示「当前还可以选择的数字中最大的那个」，即可选范围是 1..i。

            例如最开始 dfs(n)，表示可以从 1..n 中任意挑选。
            每选走一个数字 j，剩余可选的就更小，所以递归时传入 j - 1。
            """
            # d = 还差几个数字才能凑成长度为 k 的组合
            # 把 d 提前算出来，后面既用于判断，也用于控制循环下界（剪枝）
            d = k - len(path)

            # ---------- 剪枝写法一：显式剪枝（当前被注释掉，但和写法二等价）----------
            # 如果「可选数字的最大值 i」都比「还需要的个数 d」小，
            # 说明剩下的数字全选上也不够 k 个，这条分支不可能有解，直接回退。
            #
            # 举例：n = 4, k = 2，假设已经选了 4，此时 i = 3, d = 1；
            #       若某分支变成 i = 2, d = 3（要选 3 个，但只有 1、2 两个数可选），
            #       那么无论怎么选都凑不满，可以直接 return，省掉后面全部递归。
            #
            # if i < d:
            #     return

            # 递归终止条件：已经选够 k 个数字，当前 path 就是一个合法组合
            if len(path) == k:
                # 复制一份，避免后续回滚时把已保存的结果改掉
                ans.append(path.copy())
                return

            # ---------- 剪枝写法二：用循环下界剪枝（当前代码实际采用）----------
            # 这一层枚举「当前要选的数字」j，范围是从 i 递减到某个下界。
            #
            # 剪枝推导（关键）：
            #   1) 现在已经选了，还差 d 个数字没选；
            #   2) 如果这一层选择 j，那么剩下的 d - 1 个数字只能从 1..j-1 里选，
            #      也就是说后面最多还能提供 j - 1 个数字；
            #   3) 要凑够 d - 1 个，就必须满足 j - 1 >= d - 1，即 **j >= d**。
            #
            # 反过来看：如果 j < d（例如 d = 2 却去选 j = 1），
            # 选完只剩 0 个数字可用，却还需要 1 个，这条分支必然凑不满 k 个，
            # 属于无效分支，根本不用进入递归。
            #
            # 所以 j 的最小合法取值就是 d，循环下界写成 d 即可 —— 这就是剪枝。
            #
            # range(i, d - 1, -1) 的含义：从 i 开始每次减 1，直到 d（包含 d）。
            # 因为 range 的终点是开区间，写 d - 1 才刚好把 d 包含进来。
            # 例如 i = 4, d = 2 时得到 j = 4, 3, 2，正好跳过 j = 1 这种没用的分支。
            #
            # 【关于原来那句「如果用上面的 i < d，这里也可以只迭代到 d - 1」】
            # 实测结论（n = 4, k = 2）：
            #   * 下界取 d           -> 6 个组合，正确（最优，递归调用最少）
            #   * 下界取 d-1，无剪枝 -> 10 个组合，多出 [4,0] [3,0] [2,0] [1,0] 等非法结果
            #   * 下界取 d-1 + 显式剪枝 -> 6 个组合，正确（每层多一次立刻返回的无效调用）
            # 也就是说：d-1 只有在 **同时开启** i < d 剪枝时才安全，
            # 因为越界的那一次递归会被剪枝立刻挡回去；少了剪枝就会把 j 一路退到 0，
            # 而 0 并不在 1..n 范围内，于是产生非法组合。
            # 所以两种写法「显式剪枝」和「循环下界 = d」是同一个约束的两种表达，
            # 至少要保留其中一个；本代码单独用循环下界就已经足够。
            for j in range(i, d - 1, -1):
                # 选择 j 加入当前组合
                path.append(j)
                # 继续往更小的数字里选；传入 j - 1 保证不会重复选同一个数
                dfs(j - 1)
                # 回滚：撤销选择，让 j 的下一个候选值继续尝试
                path.pop()

        # 从最大的数字 n 开始选，此时可选范围是 1..n
        dfs(n)
        return ans


if __name__ == "__main__":
    s = Solution()
    n, k = 4, 2
    result = s.combine(n, k)
    print(result)  # 输出 [[4, 3], [4, 2], [4, 1], [3, 2], [3, 1], [2, 1]]