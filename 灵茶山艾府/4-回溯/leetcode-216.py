from typing import List


class Solution:
    def combinationSum3(self, k: int, n: int) -> List[List[int]]:
        """
        从 1..9 中选出 k 个互不相同的数字，使它们的和等于 n，返回所有组合。

        例如 k = 3, n = 7 时返回 [[4, 2, 1]]（4 + 2 + 1 = 7）。

        属于「组合型回溯」：从大到小依次挑数字，选过的不能再选，
        同时用「剩余和」 t 配合两个剪枝提前砍掉不可能的分支。
        """
        # 保存所有满足条件的组合
        ans = []
        # 当前正在构建的组合
        path = []

        def dfs(i: int, t: int) -> None:
            """
            i：当前还能选择的最大数字，即可选范围是 1..i
            t：剩余目标和，即还需要凑出多少（初始为 n，每选一个 j 就减去 j）
            """
            # d = 还差几个数字才能凑满 k 个
            d = k - len(path)

            # ---------- 剪枝一：剩余和已经小于 0 ----------
            # 可选数字全是正数，所以每选一个 t 只会越来越小，不可能再回升到 0。
            # 因此 t < 0 的分支必然凑不出和 n，直接回退。
            if t < 0:
                return

            # ---------- 剪枝二：剩余和超过了「理论上界」----------
            # 此刻还差 d 个数字，而能选的最大数字是 i，
            # 那么这 d 个数最多就是 i, i-1, ..., i-d+1 这 d 个最大的数。
            #
            # 这是首项 i、末项 i-d+1、项数 d 的等差数列，其和为：
            #     d * (i + (i - d + 1)) / 2  =  d * (2i - d + 1) / 2
            # 也就是代码里的 (i * 2 - d + 1) * d // 2。
            #
            # 若剩余目标 t 比这个上界还大，说明即使把最大的 d 个数全选上
            # 也达不到 t，这条分支无解，直接剪掉。
            #
            # 举例：i = 9, d = 3 时上界 = 9 + 8 + 7 = 24；
            #       若此时 t = 25，怎么选都不可能凑到，剪枝立即返回。
            if t > (i * 2 - d + 1) * d // 2:
                return

            # ---------- 终点：已经选够 k 个数字 ----------
            # 关键细节：走到这里时 d = 0，上面的上界公式恰好退化为 0，
            # 于是「t > 0 就返回」与剪枝一的「t < 0 就返回」合起来，
            # 等价于「只有 t == 0 才能到达这一行」。
            # 也就是说，剪枝条件顺便完成了终点 t == 0 的合法性校验，
            # 所以这里不需要再单独写 if t == 0。
            if len(path) == k:
                ans.append(path.copy())
                return

            # ---------- 循环下界 d：剪掉「数字个数不够」的分支 ----------
            # 推导与 leetcode-77 相同：这一层若选 j，剩下的 d - 1 个数只能从
            # 1..j-1 中取，最多只有 j - 1 个，要凑够 d - 1 个必须满足 j >= d，
            # 所以 j 的下界就是 d（range 终点开区间，故写 d - 1）。
            #
            # 附带好处：当 i < d（可选数字比需要的还少）时，
            # range(i, d - 1, -1) 刚好为空，连一次递归都不会进入，
            # 「个数不够」这层剪枝也就自动完成了。
            #
            # （可选加强）还能再加一个下界剪枝：最小的 d 个数之和为 1+2+...+d，
            # 若 t < d * (d + 1) // 2 同样无解。实测能进一步减少递归，
            # 例如 k = 4, n = 20 时调用次数从 102 降到 89。
            for j in range(i, d - 1, -1):
                path.append(j)
                # 选走 j 后：剩余目标变成 t - j，可选范围缩小到 1..j-1
                dfs(j - 1, t - j)
                # 回滚：撤销选择，换下一个 j 继续尝试
                path.pop()

        # 从最大的数字 9 开始选，此时可选范围是 1..9，剩余目标和为 n
        dfs(9, n)
        return ans


if __name__ == "__main__":
    s = Solution()
    k = 3
    n = 7
    result = s.combinationSum3(k, n)
    print(result)  # 输出所有组合，即 [[4, 2, 1]]